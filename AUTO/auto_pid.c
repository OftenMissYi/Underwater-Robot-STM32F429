/*x属于[-1,1]，输入当前角度差和准备旋转时的角度差，输出期望角速度*/
float angel_speed(const float error_angel, const float max_error_angel, int i)
{
	float output;
	int x;
	if(error_angel < 0)
		x = (int)(50 * error_angel / max_error_angel) + 50;
	if(error_angel >= 0)
		x = (int)(50 * error_angel / max_error_angel) + 50;
	if(x < 0) x = 0;
	if(x > 100) x = 100;
	
	output = (K_Angel_Speed[i] * max_error_angel) * X_Y[x];
	
	return output;
}

/*算出PWM增量，输入期望角速度与当前角速度差*/
int PI_Calc(PidObject* pid, const float error_angel_speed) 
{
	int output; 
	pid->error = error_angel_speed;  
	output = (int)(pid->kp * pid->error - pid->kd * pid->prevError);	
	pid->prevError = pid->error;
	
	return output;
}




